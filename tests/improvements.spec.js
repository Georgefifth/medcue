import { test, expect } from '@playwright/test';
import { readFile } from 'node:fs/promises';
import { importSrt } from '../src/core.js';
test.beforeEach(async ({ page }) => {
  await page.route('**/api/config', r => r.fulfill({ json: { enabled: false } }));
  await page.route('**/api/review', r => r.abort());
  await page.goto('/');
});
test('empty-cue preview cancels safely and explicit import audits omissions', async ({ page }) => {
  await page.getByRole('button', { name: 'Explore a sample review' }).click();
  const raw = await readFile('evaluation/public-audio/naloxone.srt');
  await page.locator('#srt-file').setInputFiles({ name: 'NLM-naloxone.srt', mimeType: 'text/plain', buffer: raw });
  await expect(page.getByRole('dialog')).toContainText('90 nonempty cues and 1 empty');
  await expect(page.locator('#empty-cues')).toContainText('Cue 91: 00:05:36,000');
  await page.getByRole('button', { name: 'Cancel import' }).click();
  await expect(page.locator('#cue-count')).toHaveText('5');
  await page.locator('#srt-file').setInputFiles({ name: 'NLM-naloxone.srt', mimeType: 'text/plain', buffer: raw });
  page.once('dialog', d => d.accept());
  await page.getByRole('button', { name: 'Import 90 cues without empty entries' }).click();
  await expect(page.locator('#cue-count')).toHaveText('90');
  await page.locator('.audit-panel').evaluate(el => el.open = true);
  await expect(page.locator('#audit-list')).toContainText('Explicitly omitted empty source cues: 91');
  await page.getByRole('button', { name: 'Export SRT', exact: true }).click();
  const pending = page.waitForEvent('download'); await page.getByRole('button', { name: 'Download SRT' }).click();
  const result = importSrt(await readFile(await (await pending).path(), 'utf8'));
  const reference = importSrt(await readFile('evaluation/public-audio/naloxone-review.srt', 'utf8'));
  expect(result).toEqual(reference);
});
test('typing keeps the same field, including composition, and undo restores the edit group', async ({ page }) => {
  await page.getByRole('button', { name: 'Explore a sample review' }).click();
  const original = await page.locator('#cue-text').inputValue();
  const handle = await page.locator('#cue-text').elementHandle();
  await page.locator('#cue-text').press('End');
  await page.locator('#cue-text').pressSequentially(' edited', { delay: 5 });
  expect(await handle.evaluate(el => el === document.querySelector('#cue-text'))).toBe(true);
  await page.locator('#cue-text').dispatchEvent('compositionstart');
  await page.locator('#cue-text').pressSequentially(' text');
  await page.locator('#cue-text').dispatchEvent('compositionend');
  expect(await handle.evaluate(el => el === document.querySelector('#cue-text'))).toBe(true);
  await expect(page.locator('#cue-text')).toBeFocused();
  await page.getByRole('button', { name: 'Undo', exact: true }).click();
  await expect(page.locator('#cue-text')).toHaveValue(original);
});
test('review and next is one action, respects a search, and undo restores the decision', async ({ page }) => {
  await page.getByRole('button', { name: 'Explore a sample review' }).click();
  await page.getByRole('button', { name: 'Review & next', exact: true }).click();
  await expect(page.locator('.cue-number')).toHaveText('Cue 02');
  await expect(page.locator('#progress')).toContainText('1 of 5');
  await expect(page.locator('#cue-text')).toBeFocused();
  await expect(page.locator('.source-context')).toContainText('meta formin');
  await expect(page.locator('.source-context')).toContainText('hypo glycemia');
  await page.getByRole('button', { name: 'Undo', exact: true }).click();
  await expect(page.locator('#progress')).toContainText('0 of 5');
  await page.locator('#search').fill('recording');
  await page.locator('#cue-text').focus();
  await page.locator('#cue-text').press('Control+Enter');
  await expect(page.locator('#toast')).toContainText('No more unreviewed cues in this view');
  await expect(page.locator('.cue-number')).toHaveText('Cue 02');
  await expect(page.locator('#progress')).toContainText('1 of 5');
});
test('one-click real sample loads matching audio, fails recoverably and never asks AI', async ({ page }) => {
  const posts = []; page.on('request', r => { if (r.method() === 'POST') posts.push(r.url()); });
  await page.route('**/sample/antibiotics.mp3', r => r.fulfill({ status: 503, body: 'Unavailable' }));
  await page.getByRole('button', { name: 'Try a real recording' }).click();
  await expect(page.locator('#toast')).toContainText('could not be loaded');
  await expect(page.locator('#cue-count')).toHaveText('0');
  await expect(page.getByRole('button', { name: 'Try a real recording' })).toBeEnabled();
  await page.unroute('**/sample/antibiotics.mp3');
  await page.getByRole('button', { name: 'Try a real recording' }).click();
  await expect(page.locator('#cue-count')).toHaveText('14');
  await expect(page.locator('#audio-status')).toContainText('00:00:37');
  await expect(page.getByRole('button', { name: 'Replay selected cue', exact: true })).toBeEnabled();
  const beforePlayback = await page.locator('#cue-text').inputValue();
  await page.locator('#cue-text').focus();
  await page.locator('#cue-text').press('Shift+Space');
  await expect(page.locator('#audio-status')).toContainText('Playing');
  await expect(page.locator('#cue-text')).toHaveValue(beforePlayback);
  await expect(page.locator('#cue-text')).toBeFocused();
  await page.reload();
  await expect(page.locator('#audio-title')).toHaveText('Attach audio to listen');
  page.once('dialog', d => d.accept());
  await page.getByRole('button', { name: 'Recording example', exact: true }).click();
  await expect(page.locator('#audio-status')).toContainText('00:00:37');
  expect(posts).toEqual([]);
  await page.screenshot({ path: 'artifacts/after-improvement.png', fullPage: true });
});
